import { ease, motion, render } from "svjeez";
import { voxel } from "svjeez/voxel";
import { CAMERA, D, H, ORIGIN, W } from "./kit";
import { Backdrop, Clouds, Glow, Moon, Night, Shadow, Snow, Stars, Sun } from "./sky";
import { island } from "./world";

const breathe = motion({ scale: 1, y: 0 }).to({ scale: 1.025, y: -5 }, D / 2, ease.inOut).to({ scale: 1, y: 0 }, D / 2, ease.inOut);

export function buildMinecraft(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Minecraft",
      desc: "A floating voxel island builds itself, grows trees and a hut, falls to night and snow, then crumbles into the void and starts again.",
      reducedMotion: { at: 26 },
      comment: "Generated by svjeez. Edit examples/minecraft/ instead of this file.",
    },
    <>
      <Backdrop />
      <Stars />
      <Sun />
      <Moon />
      <g transform={`translate(${ORIGIN.x} ${ORIGIN.y})`}>
        <Clouds />
      </g>
      <Shadow />
      <g style={{ transformBox: "view-box", transformOrigin: `${W / 2}px 350px` }} animation={breathe}>
        <g transform={`translate(${ORIGIN.x} ${ORIGIN.y})`}>{voxel.scene({ camera: CAMERA, blocks: island() })}</g>
      </g>
      <Night />
      <Glow />
      <Snow />
    </>,
  );
}

export default buildMinecraft;
