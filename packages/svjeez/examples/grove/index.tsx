import { ease, motion, render } from "svjeez";
import { D, H, W, random } from "./kit";
import { island, inside, ground } from "./island";
import {
  birch,
  blossom,
  fallenPetals,
  fern,
  flowers,
  oak,
  seed as seedGlow,
  stones,
  tuft,
  type Stand,
} from "./flora";
import { layer } from "./paint";
import {
  Backdrop,
  Birds,
  Clouds,
  Fireflies,
  Foreground,
  Mist,
  Moon,
  Motes,
  Petals,
  Shadow,
  Stars,
  Sun,
} from "./sky";

interface Spot {
  readonly x: number;
  readonly z: number;
}

const OAK = { x: -1.2, z: 0.6 } as const;
const BIRCH = { x: 3.4, z: -1.8 } as const;
const BLOSSOM = { x: -4.3, z: -1.4 } as const;

const inReach = (spot: Spot, x: number, z: number, radius: number): boolean =>
  Math.hypot(spot.x - x, spot.z - z) < radius;

const occupied: readonly (readonly [Spot, number])[] = [
  [OAK, 1.25],
  [BIRCH, 0.8],
  [BLOSSOM, 0.95],
  [{ x: 0.8, z: 2.7 }, 0.7],
  [{ x: -3.15, z: 0.6 }, 0.6],
  [{ x: 2.2, z: 1.6 }, 0.55],
];

const clear = (x: number, z: number, margin: number): boolean =>
  inside(x, z, 0.35) && occupied.every(([spot, radius]) => !inReach(spot, x, z, radius + margin));

const FERNS: readonly Spot[] = [
  { x: 0.75, z: 2.35 },
  { x: -3.0, z: 2.2 },
  { x: 2.55, z: 0.55 },
  { x: -0.45, z: -2.4 },
  { x: 4.15, z: 1.6 },
  { x: 1.9, z: -2.6 },
];

const FLOWERS: readonly {
  readonly spot: Spot;
  readonly kind: "cream" | "blush" | "blue";
  readonly seed: number;
}[] = [
  { spot: { x: 0.9, z: 3.25 }, kind: "cream", seed: 11 },
  { spot: { x: 2.2, z: 2.45 }, kind: "blue", seed: 23 },
  { spot: { x: -2.75, z: 1.05 }, kind: "blush", seed: 37 },
  { spot: { x: -3.6, z: 2.9 }, kind: "cream", seed: 43 },
  { spot: { x: 0.1, z: -2.05 }, kind: "blush", seed: 59 },
  { spot: { x: 3.9, z: -0.1 }, kind: "cream", seed: 67 },
  { spot: { x: -0.9, z: 3.55 }, kind: "blue", seed: 83 },
];

const scatter = (): readonly Stand[] => {
  const pick = random(1009);
  const stands: Stand[] = [];
  const placed: Spot[] = [];

  for (let attempt = 0; attempt < 900 && stands.length < 88; attempt++) {
    const x = (pick() * 2 - 1) * 5.4;
    const z = (pick() * 2 - 1) * 5.4;

    if (!clear(x, z, 0.1)) continue;

    if (placed.some((spot) => Math.hypot(spot.x - x, spot.z - z) < 0.3)) continue;
    placed.push({ x, z });
    stands.push(tuft(ground(x, z), 2000 + stands.length));
  }

  return stands;
};

const TUFTS = scatter();

const stands = (): readonly Stand[] => [
  seedGlow(ground(OAK.x - 0.05, OAK.z - 0.05)),
  fallenPetals(ground(BLOSSOM.x + 0.4, BLOSSOM.z + 0.9), 611),
  ...TUFTS,
  ...FERNS.map((spot, i) => fern(ground(spot.x, spot.z), 400 + i * 7)),
  ...FLOWERS.map(({ spot, kind, seed }) => flowers(ground(spot.x, spot.z), seed, kind)),
  stones(ground(0.95, 2.55), 701),
  stones(ground(2.35, -0.15), 733),
  birch(ground(BIRCH.x, BIRCH.z)),
  blossom(ground(BLOSSOM.x, BLOSSOM.z)),
  oak(ground(OAK.x, OAK.z)),
];

const bob = motion({ y: 0 })
  .to({ y: -5 }, D / 2, ease.inOut)
  .to({ y: 0 }, D / 2, ease.inOut);

export function buildGrove(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Grove",
      desc: "A floating island wakes at dawn. From a single seed a procedurally grown oak, birch and blossom tree unfurl tapered limbs and hundreds of individually lit leaves, while ferns, wildflowers and grass fill the moss below. The canopy breathes with the wind, petals fall, fireflies return at dusk, and the grove sinks back into the dark.",
      reducedMotion: { at: 13.5 },
      comment: "Generated by svjeez. Edit examples/grove/ instead of this file.",
    },
    <>
      <Backdrop />
      <Stars />
      <Moon />
      <Sun />
      <Clouds />
      <Birds />
      <Mist />
      <Shadow />
      <g style={{ transformBox: "view-box", transformOrigin: "480px 500px" }} animation={bob}>
        {island()}
        {layer(stands())}
      </g>
      <Petals />
      <Motes />
      <Fireflies />
      <Foreground />
    </>,
  );
}

export default buildGrove;
