import { draw, el, enter, render, type Attrs, type Color, type SvgNode } from "svjeez";

const D = 10;
const SIZE = 440;
const BOARD = { x: 40, y: 40, cell: 120 };

const C = {
  bg: "#0B0907",
  grid: "#2E2820",
  x: "#D6A96D",
  o: "#9AAFC5",
  win: "#EFE7D8",
  caption: "#8C8377",
} as const;

type Cell = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8;

const MOVES: Cell[] = [4, 1, 0, 8, 6, 2, 3];
const WIN: [Cell, Cell] = [0, 6];

const moveAt = (turn: number): number => 1.6 + turn * 0.8;
const winAt = moveAt(MOVES.length) + 0.1;
const OUT = { at: 9.2, over: 0.5 };

const center = (cell: Cell) => ({
  x: BOARD.x + (cell % 3) * BOARD.cell + BOARD.cell / 2,
  y: BOARD.y + Math.floor(cell / 3) * BOARD.cell + BOARD.cell / 2,
});

const ink = (color: Color, width: number): Attrs<"path"> => ({
  fill: "none",
  stroke: color,
  strokeWidth: width,
  strokeLinecap: "round",
});

function Grid(): SvgNode {
  const { x, y, cell } = BOARD;
  const end = 3 * cell;

  const lines = [
    `M${x + cell} ${y}V${y + end}`,
    `M${x + 2 * cell} ${y}V${y + end}`,
    `M${x} ${y + cell}H${x + end}`,
    `M${x} ${y + 2 * cell}H${x + end}`,
  ];

  return (
    <>
      {lines.map((d, index) =>
        el.path({ d, ...ink(C.grid, 4), animation: draw({ at: 0.2 + index * 0.15, over: 0.6 }) }),
      )}
    </>
  );
}

const cross = (cell: Cell, at: number): SvgNode[] => {
  const { x, y } = center(cell);
  const r = 30;

  return [
    el.path({
      d: `M${x - r} ${y - r}L${x + r} ${y + r}`,
      ...ink(C.x, 10),
      animation: draw({ at, over: 0.22 }),
    }),
    el.path({
      d: `M${x + r} ${y - r}L${x - r} ${y + r}`,
      ...ink(C.x, 10),
      animation: draw({ at: at + 0.18, over: 0.22 }),
    }),
  ];
};

const nought = (cell: Cell, at: number): SvgNode => {
  const { x, y } = center(cell);

  return el.circle({
    cx: x,
    cy: y,
    r: 32,
    transform: `rotate(-90 ${x} ${y})`,
    ...ink(C.o, 10),
    animation: draw({ at, over: 0.4 }),
  });
};

function WinLine(): SvgNode {
  const from = center(WIN[0]);
  const to = center(WIN[1]);
  const reach = 46;

  return el.path({
    d: `M${from.x} ${from.y - reach}L${to.x} ${to.y + reach}`,
    ...ink(C.win, 8),
    animation: draw({ at: winAt, over: 0.5 }),
  });
}

export function buildTicTacToe(): string {
  return render(
    {
      width: SIZE,
      height: SIZE + 40,
      duration: D,
      title: "Tic-tac-toe",
      desc: "X takes the center, forks the board, and wins down the left column.",
      css: `.mono{font-family:ui-monospace,SFMono-Regular,"SF Mono",Menlo,Consolas,monospace;letter-spacing:2px}`,
      reducedMotion: { at: winAt + 1 },
      comment: "Generated by svjeez. Edit examples/tictactoe/index.tsx instead of this file.",
    },
    <>
      <rect width={SIZE} height={SIZE + 40} rx={20} fill={C.bg} />
      <g animation={enter({ at: 0, over: 0.2 }).at(OUT.at).to({ opacity: 0 }, OUT.over)}>
        <Grid />
        {MOVES.map((cell, turn) =>
          turn % 2 === 0 ? cross(cell, moveAt(turn)) : nought(cell, moveAt(turn)),
        )}
        <WinLine />
        <text
          x={SIZE / 2}
          y={SIZE + 6}
          class="mono"
          fontSize={14}
          fill={C.caption}
          textAnchor="middle"
          animation={enter({ at: winAt + 0.3, over: 0.4 }, { opacity: 0, y: 6 })}
        >
          X WINS
        </text>
      </g>
    </>,
  );
}

export default buildTicTacToe;
