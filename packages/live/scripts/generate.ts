// Writes src/skill-errors.ts: the "Runtime errors." table from svjeez's scene-writing skill, as text, so the published
// package carries the fixes without reaching into svjeez's files. A test fails when the skill and this copy differ.
import { readFileSync, writeFileSync } from "node:fs";
import { errorTable } from "../src/fixes";

const skill = readFileSync(new URL("../../svjeez/skills/svjeez/SKILL.md", import.meta.url), "utf8");

writeFileSync(
  new URL("../src/skill-errors.ts", import.meta.url),
  `// Generated by \`bun run generate\` from svjeez's skills/svjeez/SKILL.md. Do not edit.\nexport default ${JSON.stringify(errorTable(skill))};\n`,
);
