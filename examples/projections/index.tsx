import { project, reproject, trueSize, type Topology } from "@svjeez/geo";
import { geoEqualEarth, geoMercator } from "d3-geo";
import { def, ease, motion, rect, render, type PathData } from "svjeez";
import { variables } from "svjeez/extras";
import { createRequire } from "node:module";
import { geist, geistMono } from "../fonts/faces";

const countries: Topology = createRequire(import.meta.url)("world-atlas/countries-110m.json");

const W = 960;
const H = 540;
const D = 16;

const { vars: C, css } = variables(
  {
    bg: "#08121C",
    land: "#1E3A4E",
    green: "#5FD38D",
    text: "#E8EEF2",
    dim: "#93AAB9",
  },
  {
    bg: "#EEF2F5",
    land: "#C5D3DD",
    green: "#1F9254",
    text: "#13202A",
    dim: "#5A6F7D",
  },
);

const frame = rect(300, 30, 640, 480);
const filter = (f: { properties: { name?: string } | null }) => f.properties?.name !== "Antarctica";
const mercator = geoMercator();

const maps = reproject(countries, [mercator, geoEqualEarth()], { frame, filter });

/** The same Mercator projection, left as reproject() fitted it, so the sliding outline lands on the map. */
const flat = project(countries, { frame, projection: mercator, fit: false, filter });

const greenland = maps.region("Greenland");

/** Seconds: the morph to equal area, the morph back, then the slide to the equator. */
const TO_AREA = 1.6;
const BACK = 6.2;
const MORPH = 1.8;
const SLIDE = 8.6;
const OVER = 3.4;
const FADE = 14.6;

const morph = (a: PathData, b: PathData) =>
  motion({ d: a })
    .at(TO_AREA)
    .to({ d: b }, MORPH, ease.inOut)
    .at(BACK)
    .to({ d: a }, MORPH, ease.inOut);

const slide = trueSize(flat, flat.region("Greenland"), [-12, -3], {
  at: SLIDE,
  over: OVER,
  duration: D,
});

const shown = (from: number, until: number) =>
  motion({ opacity: 0 })
    .at(from)
    .to({ opacity: 1 }, 0.5, ease.out)
    .at(until)
    .to({ opacity: 0 }, 0.4, ease.in);

const clip = def.clipPath({}, <rect x={frame.x} y={frame.y} width={frame.w} height={frame.h} />);

interface Note {
  readonly from: number;
  readonly until: number;
  readonly kicker: string;
  readonly title: string;
  readonly lines: readonly string[];
}

const NOTES: readonly Note[] = [
  {
    from: 0,
    until: TO_AREA,
    kicker: "MERCATOR",
    title: "Greenland looks huge",
    lines: ["As big as Africa, on the map", "on most classroom walls."],
  },
  {
    from: TO_AREA + 0.4,
    until: BACK,
    kicker: "EQUAL EARTH",
    title: "Same land, true areas",
    lines: ["An equal-area projection shrinks", "it to a fourteenth of Africa."],
  },
  {
    from: SLIDE,
    until: FADE,
    kicker: "MERCATOR",
    title: "Slide it south",
    lines: [
      "Moved to the equator, its real",
      "outline shrinks as Mercator",
      "stops stretching it.",
    ],
  },
];

function Caption({ note }: { note: Note }) {
  return (
    <g
      fontFamily={geist}
      animation={
        note.from === 0
          ? motion({ opacity: 1 }).at(note.until).to({ opacity: 0 }, 0.4, ease.in)
          : shown(note.from, note.until)
      }
    >
      <text x={40} y={206} fontFamily={geistMono} fontSize={11} letterSpacing={2.2} fill={C.green}>
        {note.kicker}
      </text>
      <text x={40} y={244} fontSize={28} fontWeight={600} letterSpacing={-1} fill={C.text}>
        {note.title}
      </text>
      {note.lines.map((line, i) => (
        <text x={40} y={274 + i * 20} fontSize={14} fill={C.dim}>
          {line}
        </text>
      ))}
    </g>
  );
}

export default function build(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Greenland isn't that big",
      desc: "A world map morphs from Mercator to the equal-area Equal Earth projection and back, and Greenland shrinks to its true size. Then Greenland's real outline slides down to the equator on the Mercator map, shrinking as it goes, to sit beside Africa.",
      reducedMotion: { at: 4.5 },
      css,
      comment: "Generated by svjeez. Edit examples/projections/ instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.bg} />
      <g clipPath={clip}>
        <path d={maps.land[0]} animation={morph(maps.land[0]!, maps.land[1]!)} fill={C.land} />
        <path
          d={greenland.d[0]}
          animation={morph(greenland.d[0]!, greenland.d[1]!)}
          fill={C.green}
        />
        <g animation={shown(SLIDE - 0.3, FADE)}>
          <path {...slide} fill={C.green} stroke={C.bg} strokeWidth={1} />
        </g>
      </g>
      {NOTES.map((note) => (
        <Caption note={note} />
      ))}
    </>,
  );
}
