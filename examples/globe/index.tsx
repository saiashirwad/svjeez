import { globe, sun, type LonLat, type Topology } from "@svjeez/geo";
import { def, enter, fx, rect, render } from "svjeez";
import { variables } from "svjeez/extras";
import { createRequire } from "node:module";
import { geist, geistMono } from "../fonts/faces";

const countries: Topology = createRequire(import.meta.url)("world-atlas/countries-110m.json");

const W = 960;
const H = 540;

/** One turn of the globe: a day in 24 seconds. */
const D = 24;
const R = 226;

/** The June solstice, at midnight UTC. Each second of the scene is an hour. */
const DAY = Date.UTC(2026, 5, 21);
const at = (t: number) => new Date(DAY + t * 3_600_000);

/** The globe turns with the sun, so night stays on the right while the Earth turns under it. */
const middle = sun(at(0))[0] + 72;

const earth = globe(countries, {
  frame: rect(656 - R, H / 2 - R, 2 * R, 2 * R),
  tilt: 22,
  spin: { from: middle, to: middle - 360, over: D },
  simplify: 0.8,
});

const { vars: C, css } = variables(
  {
    space: "#04060C",
    sea: "#0B1A2C",
    land: "#9FCBEA",
    night: "#02050B",
    dawn: "#FF9D5C",
    city: "#FFC56B",
    text: "#EEF4FA",
    dim: "#7F93A8",
  },
  {
    space: "#EEF2F7",
    sea: "#D6E4F0",
    land: "#2E5878",
    night: "#0A1828",
    dawn: "#E8590C",
    city: "#C25E00",
    text: "#0F1E2C",
    dim: "#5B6F82",
  },
);

const CITIES: readonly { readonly name: string; readonly at: LonLat }[] = [
  { name: "London", at: [-0.13, 51.51] },
  { name: "Cairo", at: [31.24, 30.04] },
  { name: "Delhi", at: [77.21, 28.61] },
  { name: "Tokyo", at: [139.69, 35.69] },
  { name: "Sydney", at: [151.21, -33.87] },
  { name: "São Paulo", at: [-46.63, -23.55] },
  { name: "New York", at: [-74.0, 40.71] },
  { name: "Los Angeles", at: [-118.24, 34.05] },
];

const clip = def.clipPath({}, <path d={earth.sphere} />);
const { x: cx, y: cy } = earth.center;

export default function build(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "A day on a turning globe",
      desc: "A globe with real country outlines turns once through the 24 hours of the June solstice. Night covers the right side and its edge glows orange, and eight cities ride the globe with their names, fading out as they pass behind it.",
      reducedMotion: { at: 12 },
      css,
      comment: "Generated by svjeez. Edit examples/globe/ instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.space} />
      <circle cx={cx} cy={cy} r={R + 14} fill={C.land} opacity={0.06} filter={fx.blur(10)} />
      <path d={earth.sphere} fill={C.sea} />
      <g clipPath={clip}>
        {earth.land().map((piece) => (
          <path {...piece} fill={C.land} />
        ))}
        <path {...earth.night(at)} fill={C.night} opacity={0.6} />
        <path
          {...earth.terminator(at)}
          fill="none"
          stroke={C.dawn}
          strokeWidth={10}
          opacity={0.35}
          filter={fx.blur(6)}
        />
      </g>
      <path d={earth.sphere} fill="none" stroke={C.land} strokeOpacity={0.3} strokeWidth={1} />
      {CITIES.map((city) => (
        <g {...earth.place(city.at)}>
          <circle r={3} fill={C.city} />
          <text x={6} y={-6} fontFamily={geist} fontSize={11} fontWeight={600} fill={C.text}>
            {city.name}
          </text>
        </g>
      ))}
      <g fontFamily={geist} animation={enter({ at: 0.2, over: 1 }, { y: 10 })}>
        <text x={64} y={210} fontFamily={geistMono} fontSize={11} letterSpacing={2.4} fill={C.dawn}>
          21 JUNE 2026
        </text>
        <text x={64} y={254} fontSize={36} fontWeight={600} letterSpacing={-1.4} fill={C.text}>
          A day, turning
        </text>
        <text x={64} y={284} fontSize={14} fill={C.dim}>
          Real coastlines on a globe that turns
        </text>
        <text x={64} y={304} fontSize={14} fill={C.dim}>
          once, with night on the right.
        </text>
      </g>
    </>,
  );
}
