import * as tabler from "@svjeez/icons/tabler";
import { draw, ease, Icon, motion, render, span, type IconData, variables } from "svjeez";
import { defaults, list, text, type Values } from "svjeez/params";

const W = 640;
const H = 360;
const D = 5;

const { vars: C, css } = variables({
  dark: { page: "#10151C", card: "#18202A", line: "#26323F", ink: "#E8EEF4", accent: "#FF6B57" },
  light: { page: "#EEF1F4", card: "#FFFFFF", line: "#D5DCE3", ink: "#1B2530", accent: "#E5432D" },
});

const COLUMNS = 4;
const SIZE = 64;
const CELL = 128;
const LEFT = (W - COLUMNS * CELL) / 2;

const NAME = {
  maxLength: 40,
  label: "A Tabler icon name, as on tabler.io/icons: arrow-left, brand-github",
};

export const params = {
  title: text("Icons", { maxLength: 60 }),
  desc: text(
    "Seven Tabler outline icons draw themselves in one stroke at a time, then a filled heart pops into the last place in the grid.",
    { maxLength: 300, label: "What the icons show, for screen readers" },
  ),
  outlines: list(text("", NAME), ["rocket", "bolt", "bell", "cloud", "moon", "search", "mail"], {
    min: 1,
    max: 7,
    label: "Outline icons that draw on in turn",
  }),
  pop: text("heart-filled", {
    ...NAME,
    label: "The icon that pops into the next place, often a filled one",
  }),
  popLabel: text("Heart", {
    maxLength: 40,
    label: "What the popping icon means, for screen readers",
  }),
};

// SAFETY: the module's exports are all icons.
const icons = tabler as Readonly<Record<string, IconData>>;

const iconOf = (name: string, path: string): IconData => {
  const key = name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

  if (!Object.hasOwn(icons, key))
    throw new Error(
      `${path} "${name}" is not a Tabler icon. Use a name from tabler.io/icons, such as "arrow-left".`,
    );

  return icons[key]!;
};

const place = (index: number, top: number) => ({
  x: LEFT + (index % COLUMNS) * CELL + (CELL - SIZE) / 2,
  y: top + Math.floor(index / COLUMNS) * CELL + (CELL - SIZE) / 2,
});

function Pop({
  icon,
  index,
  top,
  alt,
}: {
  icon: IconData;
  index: number;
  top: number;
  alt: string;
}) {
  const { x, y } = place(index, top);
  const at = 0.3 + index * 0.3 + 0.8;

  return (
    <g
      style={{ transformOrigin: `${x + SIZE / 2}px ${y + SIZE / 2}px` }}
      animation={motion({ opacity: 0, scale: 0.3 }).to(
        { opacity: 1, scale: 1 },
        span(at, 0.55),
        ease.pop,
      )}
    >
      <Icon icon={icon} x={x} y={y} size={SIZE} fill={C.accent} alt={alt} />
    </g>
  );
}

export default function build(p: Values<typeof params> = defaults(params)): string {
  const outlines = p.outlines.map((name, i) => iconOf(name, `outlines[${i}]`));
  const rows = Math.ceil((outlines.length + 1) / COLUMNS);
  const top = (H - rows * CELL) / 2;

  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: p.title,
      desc: p.desc,
      reducedMotion: { at: D - 0.5 },
      css,
      comment: "Generated by svjeez. Edit examples/icons/ instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.page} />
      <rect
        x={LEFT - 8}
        y={top - 8}
        width={COLUMNS * CELL + 16}
        height={rows * CELL + 16}
        rx={20}
        fill={C.card}
        stroke={C.line}
      />
      {outlines.map((icon, index) => (
        <Icon
          icon={icon}
          {...place(index, top)}
          size={SIZE}
          stroke={C.ink}
          strokeWidth={1.75}
          animation={(_, each) => draw(each.stagger(span(0.3 + index * 0.3, 0.7), 0.25))}
        />
      ))}
      <Pop icon={iconOf(p.pop, "pop")} index={outlines.length} top={top} alt={p.popLabel} />
    </>,
  );
}
