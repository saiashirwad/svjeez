import { bell, bolt, cloud, heartFilled, mail, moon, rocket, search } from "@svjeez/icons/tabler";
import { draw, ease, Icon, motion, render, type IconData } from "svjeez";
import { variables } from "svjeez/extras";

const W = 640;
const H = 360;
const D = 5;

/** Each color is a CSS variable, so the card follows the viewer's light or dark mode. */
const { vars: C, css } = variables(
  { page: "#10151C", card: "#18202A", line: "#26323F", ink: "#E8EEF4", accent: "#FF6B57" },
  { page: "#EEF1F4", card: "#FFFFFF", line: "#D5DCE3", ink: "#1B2530", accent: "#E5432D" },
);

const COLUMNS = 4;
const SIZE = 64;
const CELL = 128;
const LEFT = (W - COLUMNS * CELL) / 2;
const TOP = 52;

/** Seven outlines draw in, left to right and top to bottom, a path at a time. */
const outlines: readonly IconData[] = [rocket, bolt, bell, cloud, moon, search, mail];

const place = (index: number) => ({
  x: LEFT + (index % COLUMNS) * CELL + (CELL - SIZE) / 2,
  y: TOP + Math.floor(index / COLUMNS) * CELL + (CELL - SIZE) / 2,
});

const POP = 0.3 + outlines.length * 0.3 + 0.8;

function Pop({ icon, index }: { icon: IconData; index: number }) {
  const { x, y } = place(index);

  return (
    <g
      style={{ transformOrigin: `${x + SIZE / 2}px ${y + SIZE / 2}px` }}
      animation={motion({ opacity: 0, scale: 0.3 })
        .at(POP)
        .to({ opacity: 1, scale: 1 }, 0.55, ease.pop)}
    >
      <Icon icon={icon} x={x} y={y} size={SIZE} fill={C.accent} alt="Heart" />
    </g>
  );
}

export default function build(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Icons",
      desc: "Seven Tabler outline icons draw themselves in one stroke at a time, then a filled heart pops into the last place in the grid.",
      reducedMotion: { at: D - 0.5 },
      css,
      comment: "Generated by svjeez. Edit examples/icons/ instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.page} />
      <rect
        x={LEFT - 8}
        y={TOP - 8}
        width={COLUMNS * CELL + 16}
        height={2 * CELL + 16}
        rx={20}
        fill={C.card}
        stroke={C.line}
      />
      {outlines.map((icon, index) => (
        <Icon
          icon={icon}
          {...place(index)}
          size={SIZE}
          stroke={C.ink}
          strokeWidth={1.75}
          animation={(_, path) => draw({ at: 0.3 + index * 0.3 + path * 0.25, over: 0.7 })}
        />
      ))}
      <Pop icon={heartFilled} index={outlines.length} />
    </>,
  );
}
