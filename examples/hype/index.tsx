import { ease, motion, render, type SvgNode } from "svjeez";
import { css, mono } from "../style";
import { coldOpen } from "./cold";
import { codeShot, CODE } from "./editor";
import { D, END_AT, FACTS_SPAN, facts, finale } from "./finale";
import { C, H, W } from "./kit";
import { montage, SHOTS } from "./montage";
import { TERM, terminalShot } from "./session";
import { HAND, handwriting } from "./write";

/** A hairline progress bar along the bottom edge, one tick per shot. */
const progress = (): SvgNode => {
  const ticks = [
    TERM.at,
    CODE.at,
    SHOTS.map.at,
    SHOTS.pipeline.at,
    SHOTS.spring.at,
    SHOTS.data.at,
    HAND.at,
    FACTS_SPAN.at,
    END_AT,
  ];

  return (
    <g animation={motion({ opacity: 0 }).at(TERM.at).to({ opacity: 1 }, 0.4)}>
      <rect x={0} y={H - 3} width={W} height={3} fill={C.hairline} />
      <rect
        x={0}
        y={H - 3}
        width={0}
        height={3}
        fill={C.accent}
        animation={motion({ width: 0 }).to({ width: W }, D, ease.linear)}
      />
      {ticks.map((t) => (
        <rect x={(t / D) * W - 1} y={H - 9} width={2} height={6} fill={C.muted} />
      ))}
    </g>
  );
};

const scene = (size: string) =>
  render(
    {
      width: W,
      height: H,
      duration: D,
      title: "svjeez",
      desc: "A one-minute reel for svjeez that follows the viewer's light or dark mode. In Claude Code, Claude reads the svjeez skill, writes a scene, renders frames, looks at them and ships an SVG. The scene's TSX, highlighted by @svjeez/code, streams into an editor while a preview draws each line's effect. Four shots each compose several packages: a dot map of the world with routes and dots in flight beside two counters that tick up; Mermaid text typed into an editor while it becomes a flowchart; a damped spring's equation typeset and braced, then the spring bouncing beside its plot; and one dataset drawn as a bar chart with a trend line and as a voxel skyline. \"Write anything.\" is inked on over a field of streamlines. Three facts: zero bytes of runtime JS, one self-contained file, CSS and SMIL. The svjeez logo draws on above the install command and a row of the packages.",
      css,
      reducedMotion: { at: D - 1 },
      comment: "Generated by svjeez. Edit examples/hype/index.tsx instead of this file.",
    },
    <g fontFamily={mono}>
      <rect width={W} height={H} fill={C.page} />
      {coldOpen}
      {terminalShot}
      {codeShot}
      {montage}
      {handwriting}
      {facts}
      {finale(size)}
      {progress()}
      <rect
        width={W}
        height={H}
        fill={C.page}
        animation={motion({ opacity: 0 })
          .at(D - 0.7)
          .to({ opacity: 1 }, 0.6, ease.in)}
      />
    </g>,
  );

/** The finale names the file's own size, so render to measure it. */
export default function build(): string {
  const kb = (svg: string) => `${Math.round(new TextEncoder().encode(svg).length / 1024)} KB`;

  return scene(kb(scene(kb(scene("000 KB")))));
}
