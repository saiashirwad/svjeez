import {
  draw,
  ease,
  enter,
  fx,
  motion,
  render,
  span,
  wiggle,
  type Child,
  type Color,
} from "svjeez";

import { HEIGHT, MARGIN, RADIUS, WIDTH, color, css, hue, mono, size, wash } from "../gallery-style";

const W = WIDTH;
const H = HEIGHT;
const D = 8;

/** Six tiles in a 3 by 2 grid inside the margins. Each effect is drawn in a 200 by 180 box and scaled up to fill its tile. */
const GAP = 12;
const TILE = { w: (W - 2 * MARGIN - 2 * GAP) / 3, h: (H - 2 * MARGIN - GAP) / 2 };
const ZOOM = 1.15;

/** Three hues: each tile is washed in its own, and its effect is drawn in the same one. */
const C = {
  bg: color.bg,
  tile: color.panel,
  label: color.dim,
  blue: hue.blue,
  orange: hue.orange,
  purple: hue.purple,
} as const;

const glow = fx.glow({ blur: 4 });
const boil = fx.boil({ strength: 2.5, rate: 8 });

function Tile({
  col,
  row,
  label,
  tint,
  children,
}: {
  col: number;
  row: number;
  label: string;
  tint: Color;
  children: Child;
}) {
  return (
    <g transform={`translate(${MARGIN + col * (TILE.w + GAP)} ${MARGIN + row * (TILE.h + GAP)})`}>
      <rect width={TILE.w} height={TILE.h} rx={RADIUS} fill={C.tile} />
      <rect
        width={TILE.w}
        height={TILE.h}
        rx={RADIUS}
        {...wash(tint, 0.1)}
        stroke={tint}
        strokeOpacity={0.4}
      />
      <g transform={`translate(${(TILE.w - 200 * ZOOM) / 2} 4) scale(${ZOOM})`}>{children}</g>
      <text x={16} y={TILE.h - 16} fontFamily={mono} fontSize={size.label} fill={C.label}>
        {label}
      </text>
    </g>
  );
}

export function buildEffects(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Motion effects",
      desc: "Six tiles: a word that blurs in and out, a jittering square, a drifting orb, a hand-drawn boiling sketch, a flickering neon sign, and a looping spinner.",
      css,
      reducedMotion: { at: 4 },
      comment: "Generated by svjeez. Edit examples/effects/index.tsx instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.bg} />
      <Tile col={0} row={0} label="Blur in and out" tint={C.blue}>
        <text
          x={100}
          y={92}
          fontFamily={mono}
          fontSize={40}
          fill={C.blue}
          textAnchor="middle"
          animation={enter({ at: 0.4, over: 0.9 }, { opacity: 0, blur: 10 }).to(
            { opacity: 0, blur: 10 },
            span(6.4, 0.9),
          )}
        >
          Blur
        </text>
      </Tile>
      <Tile col={1} row={0} label="Jitter" tint={C.orange}>
        <rect
          x={66}
          y={44}
          width={68}
          height={68}
          rx={8}
          fill={C.orange}
          animation={wiggle(
            { x: 3, y: 3, rotate: 8 },
            { seed: "jitter", rate: 12, ease: ease.hold },
          )}
        />
      </Tile>
      <Tile col={2} row={0} label="Drift" tint={C.purple}>
        <circle
          cx={100}
          cy={78}
          r={30}
          fill={C.purple}
          animation={wiggle({ x: 14, y: 10, scale: 0.12 }, { seed: "drift", rate: 1.5, period: 3 })}
        />
      </Tile>
      <Tile col={0} row={1} label="Hand-drawn line" tint={C.orange}>
        <g
          filter={boil}
          fill="none"
          stroke={C.orange}
          strokeWidth={3}
          strokeLinecap="round"
          strokeLinejoin="round"
        >
          <path d="M40 120V70L100 30L160 70V120Z" animation={draw({ at: 0.3, over: 1.2 })} />
          <path d="M85 120V90H115V120" animation={draw({ at: 1.2, over: 0.6 })} />
        </g>
      </Tile>
      <Tile col={1} row={1} label="Neon flicker" tint={C.purple}>
        <text
          x={100}
          y={94}
          fontFamily={mono}
          fontSize={44}
          fill={C.purple}
          textAnchor="middle"
          filter={glow}
          animation={wiggle({ opacity: 0.8 }, { seed: "flicker", rate: 14, ease: ease.hold })}
        >
          Open
        </text>
      </Tile>
      <Tile col={2} row={1} label="Spinner" tint={C.blue}>
        <circle
          cx={100}
          cy={78}
          r={34}
          fill="none"
          stroke={C.blue}
          strokeWidth={6}
          strokeLinecap="round"
          strokeDasharray="70 150"
          animation={motion().to({ rotate: 360 }, span(0, 1.5), ease.linear).loop(1.5)}
        />
        <circle
          cx={100}
          cy={78}
          r={7}
          fill={C.orange}
          animation={motion({ scale: 1 })
            .to({ scale: 1.6 }, span(0, 0.375), ease.inOut)
            .to({ scale: 1 }, span(0, 0.375).next(0.375), ease.inOut)
            .loop(0.75)}
        />
      </Tile>
    </>,
  );
}

export default buildEffects;
