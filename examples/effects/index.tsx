import { draw, ease, enter, fx, motion, render, wiggle, type Child } from "svjeez";
import { adaptive, systemDark, systemLight } from "svjeez/extras";

const W = 660;
const H = 420;
const D = 6;

const { theme, css } = adaptive({ light: systemLight, dark: systemDark });

const C = {
  bg: theme.base00,
  tile: theme.base01,
  edge: theme.base02,
  label: theme.base04,
  pink: theme.base08,
  cyan: theme.base0C,
  gold: theme.base0A,
  violet: theme.base0E,
} as const;

const CSS = `.mono{font-family:ui-monospace,SFMono-Regular,"SF Mono",Menlo,Consolas,monospace}`;

const glow = fx.glow({ blur: 4 });
const boil = fx.boil({ strength: 2.5, rate: 8 });

function Tile({
  col,
  row,
  label,
  children,
}: {
  col: number;
  row: number;
  label: string;
  children: Child;
}) {
  return (
    <g transform={`translate(${20 + col * 210} ${20 + row * 200})`}>
      <rect width={200} height={180} rx={14} fill={C.tile} stroke={C.edge} />
      <text x={16} y={162} class="mono" fontSize={11} letterSpacing={1.5} fill={C.label}>
        {label}
      </text>
      {children}
    </g>
  );
}

export function buildEffects(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "svjeez effects",
      desc: "Six tiles: a word that blurs in and out, a jittering square, a drifting orb, a hand-drawn boiling sketch, a flickering neon sign, and a looping spinner.",
      css: [css, CSS].join("\n"),
      reducedMotion: { at: 3 },
      comment: "Generated by svjeez. Edit examples/effects/index.tsx instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.bg} />
      <Tile col={0} row={0} label="BLUR IN / OUT">
        <text
          x={100}
          y={92}
          class="mono"
          fontSize={40}
          fontWeight={700}
          fill={C.cyan}
          textAnchor="middle"
          animation={enter({ at: 0.4, over: 0.9 }, { opacity: 0, blur: 10 })
            .at(4.4)
            .to({ opacity: 0, blur: 10 }, 0.9)}
        >
          BLUR
        </text>
      </Tile>
      <Tile col={1} row={0} label="WIGGLE · HOLD">
        <rect
          x={66}
          y={44}
          width={68}
          height={68}
          rx={8}
          fill={C.gold}
          animation={wiggle(
            { x: 3, y: 3, rotate: 8 },
            { seed: "jitter", rate: 12, ease: ease.hold },
          )}
        />
      </Tile>
      <Tile col={2} row={0} label="WIGGLE · SMOOTH">
        <circle
          cx={100}
          cy={78}
          r={30}
          fill={C.violet}
          animation={wiggle({ x: 14, y: 10, scale: 0.12 }, { seed: "drift", rate: 1.5, period: 3 })}
        />
      </Tile>
      <Tile col={0} row={1} label="FX.BOIL + DRAW">
        <g
          filter={boil}
          fill="none"
          stroke={C.pink}
          strokeWidth={3}
          strokeLinecap="round"
          strokeLinejoin="round"
        >
          <path d="M40 120V70L100 30L160 70V120Z" animation={draw({ at: 0.3, over: 1.2 })} />
          <path d="M85 120V90H115V120" animation={draw({ at: 1.2, over: 0.6 })} />
        </g>
      </Tile>
      <Tile col={1} row={1} label="FLICKER + GLOW">
        <text
          x={100}
          y={94}
          class="mono"
          fontSize={44}
          fontWeight={700}
          fill={C.pink}
          textAnchor="middle"
          filter={glow}
          animation={wiggle({ opacity: 0.8 }, { seed: "flicker", rate: 14, ease: ease.hold })}
        >
          OPEN
        </text>
      </Tile>
      <Tile col={2} row={1} label="LOOP">
        <circle
          cx={100}
          cy={78}
          r={34}
          fill="none"
          stroke={C.cyan}
          strokeWidth={6}
          strokeLinecap="round"
          strokeDasharray="70 150"
          animation={motion().to({ rotate: 360 }, 1.5, ease.linear).loop(1.5)}
        />
        <circle
          cx={100}
          cy={78}
          r={7}
          fill={C.gold}
          animation={motion({ scale: 1 })
            .to({ scale: 1.6 }, 0.375, ease.inOut)
            .to({ scale: 1 }, 0.375, ease.inOut)
            .loop(0.75)}
        />
      </Tile>
    </>,
  );
}

export default buildEffects;
