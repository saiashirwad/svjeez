import { render } from "svg-motion";
import { Backdrop, Copy, Footer, Header, Index, Rules } from "./chrome";
import { cardClip } from "./defs";
import { DESC, THEME_CSS, TITLE } from "./theme";
import { AppWindow } from "./window";

const D = 26;

export function buildStrata(): string {
  return render(
    {
      width: 1200,
      height: 760,
      duration: D,
      title: TITLE,
      desc: DESC,
      css: THEME_CSS,
      reducedMotion: { at: 22 },
      comment: "Generated by svg-motion. Edit examples/strata/index.tsx instead of this file.",
    },
    <g clipPath={cardClip}>
      <Backdrop />
      <Header />
      <Rules />
      <Copy />
      <Index />
      <Footer />
      <AppWindow />
    </g>,
  );
}

export default buildStrata;
