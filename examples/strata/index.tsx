import { AMBIENT_CSS, Scene } from "svg-motion";
import { Backdrop, Copy, Footer, Header, Index, Rules } from "./chrome";
import { Defs } from "./defs";
import { D } from "./motion";
import { DESC, THEME_CSS, TITLE } from "./theme";
import { AppWindow } from "./window";

export function buildStrata(): string {
  const film = new Scene({
    width: 1200,
    height: 760,
    duration: D,
    title: TITLE,
    desc: DESC,
    css: THEME_CSS,
    ambientCss: AMBIENT_CSS,
    reducedMotion: { at: 22, selector: ".a, .blink, .pulse" },
    comment: "Generated by svg-motion. Edit examples/strata/index.tsx instead of this file.",
  });

  film.defs(<Defs />);
  film.add(
    <g clipPath="url(#cardClip)">
      <Backdrop />
      <Header />
      <Rules />
      <Copy />
      <Index />
      <Footer />
      <AppWindow />
    </g>,
  );

  return film.render();
}

export default buildStrata;
