import { project, type LonLat, type Topology } from "@svjeez/geo";
import { draw, ease, motion, rect, render, type Child, type SvgNode } from "svjeez";
import { Camera, flow, type CameraStop } from "svjeez/extras";
import { createRequire } from "node:module";

const countries: Topology = createRequire(import.meta.url)("world-atlas/countries-50m.json");

const W = 960;
const H = 540;
const D = 14;

const C = {
  night: "#0A1520",
  sea: "#0F2131",
  grid: "#1A3247",
  land: "#1C3A4F",
  line: "#5D8BA5",
  route: "#F4B740",
  text: "#E3ECF2",
  dim: "#8FA9BA",
} as const;

const frame = rect(24, 24, W - 48, H - 48);

const map = project(countries, {
  frame,
  filter: (f) => f.properties?.name !== "Antarctica",
});

const NEW_YORK: LonLat = [-74.0, 40.7];
const LONDON: LonLat = [-0.13, 51.5];

const route = map.route(NEW_YORK, LONDON);
const target = map.bounds([NEW_YORK, LONDON], 60);
const zoom = Math.min(W / target.w, H / target.h);

/**
 * The borders draw in as one path per country, then hand over at SWAP to a copy the camera zooms, which holds the
 * whole map in two paths. Chromium keeps each animated element on its own raster and flashes blank tiles when a camera
 * scales hundreds of them, so the copy that zooms has no animations at all.
 */
const SWAP = 3.6;
const PAN = 1.4;
const FLY = { at: 5.6, over: 3.4 } as const;

const stops: CameraStop[] = [
  { during: { at: 0, over: 4.2 }, target: "all" },
  { during: { at: 4.2, over: 6.6 }, target },
  { during: { at: 10.8, over: D - 10.8 }, target: "all" },
];

const Follow = ({ children }: { children: Child }): SvgNode => (
  <Camera frame={rect(0, 0, W, H)} stops={stops} over={PAN}>
    {children}
  </Camera>
);

/** West to east, the order each country starts to draw. */
const west = Math.min(...map.regions.map((r) => r.centroid.x));
const east = Math.max(...map.regions.map((r) => r.centroid.x));
const start = (x: number) => 0.3 + (2.2 * (x - west)) / (east - west);

function Intro(): SvgNode {
  return (
    <g strokeWidth={0.6} strokeLinejoin="round">
      {map.regions.map((r) => (
        <path
          d={r.d}
          stroke={C.line}
          animation={[
            motion({ fill: C.sea })
              .at(start(r.centroid.x) + 0.5)
              .to({ fill: C.land }, 0.6),
            draw({ at: start(r.centroid.x), over: 0.9 }),
          ]}
        />
      ))}
    </g>
  );
}

function City({ at, name, when, side }: { at: LonLat; name: string; when: number; side: 1 | -1 }) {
  const { x, y } = map.point(at);
  const size = 15 / zoom;

  return (
    <g
      animation={motion({ opacity: 0, scale: 0.4 })
        .at(when)
        .to({ opacity: 1, scale: 1 }, 0.4, ease.pop)
        .at(10.4)
        .to({ opacity: 0 }, 0.6)}
      style={{ transformOrigin: `${x}px ${y}px` }}
    >
      <circle cx={x} cy={y} r={7 / zoom} fill={C.route} opacity={0.25} />
      <circle cx={x} cy={y} r={3.5 / zoom} fill={C.route} />
      <text
        x={x + (side * 10) / zoom}
        y={y + size / 3}
        textAnchor={side === 1 ? "start" : "end"}
        fontFamily="system-ui, sans-serif"
        fontWeight={600}
        fontSize={size}
        fill={C.text}
      >
        {name}
      </text>
    </g>
  );
}

function Flight(): SvgNode {
  const trip = flow(route, {
    ...FLY,
    style: "comet",
    color: C.route,
    size: 4 / zoom,
    arrive: true,
  });

  return (
    <>
      <path
        d={route.map((p, i) => `${i ? "L" : "M"}${p.x} ${p.y}`).join("")}
        fill="none"
        stroke={C.route}
        strokeWidth={1.4 / zoom}
        opacity={0.7}
        animation={[draw(FLY, ease.linear), motion().at(10.4).to({ opacity: 0 }, 0.6)]}
      />
      {trip.node}
    </>
  );
}

export default function build(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Across the Atlantic",
      desc: "A world map draws its borders in from west to east. The view zooms to the North Atlantic, where a great-circle route arcs from New York to London, then pulls back to the whole world.",
      reducedMotion: { at: 9.5 },
      comment: "Generated by svjeez. Edit examples/world/ instead of this file.",
    },
    <>
      <rect width={W} height={H} fill={C.night} />
      <Follow>
        <path d={map.sphere} fill={C.sea} />
        <path d={map.graticule(15)} fill="none" stroke={C.grid} strokeWidth={0.5} />
      </Follow>
      <g animation={motion({ opacity: 1 }).at(SWAP).set({ opacity: 0 })}>
        <Intro />
      </g>
      <g animation={motion({ opacity: 0 }).at(SWAP).set({ opacity: 1 })}>
        <Follow>
          <path d={map.land} fill={C.land} />
          <path
            d={map.lines}
            fill="none"
            stroke={C.line}
            strokeWidth={0.6}
            strokeLinejoin="round"
          />
        </Follow>
      </g>
      <Follow>
        <City at={NEW_YORK} name="New York" when={4.9} side={-1} />
        <City at={LONDON} name="London" when={5.1} side={1} />
        <Flight />
      </Follow>
    </>,
  );
}
