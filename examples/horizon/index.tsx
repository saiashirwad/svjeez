import { ease, motion, render, shake } from "svg-motion";
import { Disk, Shock } from "./disk";
import { Flash, Hud, Lens, Reticle, Title } from "./hud";
import { D, H, T, W } from "./kit";
import { Jets, Shadow } from "./shadow";
import { Backdrop, Nebula, Stars, Warp } from "./sky";

const CSS = [
  `.sans{font-family:"Inter","SF Pro Display",system-ui,sans-serif}`,
  `.mono{font-family:ui-monospace,SFMono-Regular,"SF Mono",Menlo,monospace;font-size:10px}`,
].join("");

/** The camera pushes in through the act, kicks at ignition, and resets while the screen is black. */
const push = motion({ scale: 1 }).at(T.hud).to({ scale: 1.1 }, T.collapse - T.hud, ease.inOut).at(T.black).set({ scale: 1 });
const kick = shake({ at: T.ignite, over: 0.9 }, { x: 9, y: 6, rotate: 0.8 }, { rate: 22 });

export function buildHorizon(): string {
  return render(
    {
      width: W,
      height: H,
      duration: D,
      title: "Event Horizon",
      desc: "A black hole forms out of the dark: an accretion disk spirals together, its shadow and lensed photon ring open, jets ignite with a shockwave, a HUD tracks it, and then the camera falls through the horizon into black and the sky returns.",
      css: CSS,
      reducedMotion: { at: 6.5 },
      comment: "Generated by svg-motion. Edit examples/horizon/ instead of this file.",
    },
    <>
      <Backdrop />
      <g style={{ transformBox: "view-box", transformOrigin: `${W / 2}px ${H / 2}px` }} animation={[push, kick]}>
        <Nebula />
        <Stars />
        <g transform={`translate(${W / 2} ${H / 2})`}>
          <Disk half="far" />
          <Jets />
          <Shadow />
          <Disk half="near" />
          <Shock />
          <Reticle />
          <Warp />
        </g>
      </g>
      <Flash />
      <Hud />
      <Title />
      <Lens />
    </>,
  );
}

export default buildHorizon;
