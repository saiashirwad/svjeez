import { anim, drawWindow, revealWindow, Scene, type SvgNode } from "svg-motion";

const D = 10;
const SIZE = 440;
const BOARD = { x: 40, y: 40, cell: 120 };

const C = {
  bg: "#0B0907",
  grid: "#2E2820",
  x: "#D6A96D",
  o: "#9AAFC5",
  win: "#EFE7D8",
  caption: "#8C8377",
} as const;

type Cell = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8;

const MOVES: Cell[] = [4, 1, 0, 8, 6, 2, 3];
const WIN: [Cell, Cell] = [0, 6];

const moveAt = (turn: number): number => 1.6 + turn * 0.8;
const winAt = moveAt(MOVES.length) + 0.1;
const OUT: [number, number] = [9.2, 9.7];

const center = (cell: Cell) => ({
  x: BOARD.x + (cell % 3) * BOARD.cell + BOARD.cell / 2,
  y: BOARD.y + Math.floor(cell / 3) * BOARD.cell + BOARD.cell / 2,
});

const stroke = (color: string, width: number) => ({
  fill: "none",
  stroke: color,
  strokeWidth: width,
  strokeLinecap: "round",
  pathLength: 1,
  strokeDasharray: 1,
});

function Grid(): SvgNode {
  const { x, y, cell } = BOARD;
  const end = 3 * cell;
  const lines = [
    `M${x + cell} ${y}V${y + end}`,
    `M${x + 2 * cell} ${y}V${y + end}`,
    `M${x} ${y + cell}H${x + end}`,
    `M${x} ${y + 2 * cell}H${x + end}`,
  ];
  return (
    <>
      {lines.map((d, index) => (
        <path
          d={d}
          {...stroke(C.grid, 4)}
          animation={anim(`grid-${index}`, drawWindow({ in: [0.2 + index * 0.15, 0.8 + index * 0.15] }))}
        />
      ))}
    </>
  );
}

function X({ cell, at }: { cell: Cell; at: number }): SvgNode {
  const { x, y } = center(cell);
  const r = 30;
  return (
    <>
      <path
        d={`M${x - r} ${y - r}L${x + r} ${y + r}`}
        {...stroke(C.x, 10)}
        animation={anim(`x-${cell}-a`, drawWindow({ in: [at, at + 0.22] }))}
      />
      <path
        d={`M${x + r} ${y - r}L${x - r} ${y + r}`}
        {...stroke(C.x, 10)}
        animation={anim(`x-${cell}-b`, drawWindow({ in: [at + 0.18, at + 0.4] }))}
      />
    </>
  );
}

function O({ cell, at }: { cell: Cell; at: number }): SvgNode {
  const { x, y } = center(cell);
  return (
    <circle
      cx={x}
      cy={y}
      r={32}
      transform={`rotate(-90 ${x} ${y})`}
      {...stroke(C.o, 10)}
      animation={anim(`o-${cell}`, drawWindow({ in: [at, at + 0.4] }))}
    />
  );
}

function WinLine(): SvgNode {
  const from = center(WIN[0]);
  const to = center(WIN[1]);
  const reach = 46;
  return (
    <path
      d={`M${from.x} ${from.y - reach}L${to.x} ${to.y + reach}`}
      {...stroke(C.win, 8)}
      animation={anim("win", drawWindow({ in: [winAt, winAt + 0.5] }))}
    />
  );
}

export function buildTicTacToe(): string {
  const film = new Scene({
    width: SIZE,
    height: SIZE + 40,
    duration: D,
    title: "Tic-tac-toe",
    desc: "X takes the center, forks the board, and wins down the left column.",
    css: `.mono{font-family:ui-monospace,SFMono-Regular,"SF Mono",Menlo,Consolas,monospace;letter-spacing:2px}`,
    reducedMotion: { at: winAt + 1 },
    comment: "Generated by svg-motion. Edit examples/tictactoe/index.tsx instead of this file.",
  });

  film.add(
    <rect width={SIZE} height={SIZE + 40} rx={20} fill={C.bg} />,
    <g animation={anim("board", revealWindow({ in: [0, 0.2], out: OUT }))}>
      <Grid />
      {MOVES.map((cell, turn) =>
        turn % 2 === 0 ? <X cell={cell} at={moveAt(turn)} /> : <O cell={cell} at={moveAt(turn)} />,
      )}
      <WinLine />
      <text
        x={SIZE / 2}
        y={SIZE + 6}
        class="mono"
        fontSize={14}
        fill={C.caption}
        textAnchor="middle"
        animation={anim("caption", revealWindow({ in: [winAt + 0.3, winAt + 0.7], from: { opacity: 0, y: 6 }, to: { opacity: 1, y: 0 } }))}
      >
        X WINS
      </text>
    </g>,
  );

  return film.render();
}

export default buildTicTacToe;
